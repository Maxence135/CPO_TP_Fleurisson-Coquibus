public class Resultat {
    public int exact;
    public int haut;
    public int bas;

    public Resultat(int exact, int haut, int bas) {
        this.exact = exact;
        this.haut = haut;
        this.bas = bas;
    }

    public int getExact() {
        return exact;
    }

    public int getHaut() {
        return haut;
    }

    public int getBas() {
        return bas;
    }
    
    
}
